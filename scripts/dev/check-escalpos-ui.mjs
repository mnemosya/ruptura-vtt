import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1200, height: 1000 }, reducedMotion: 'reduce' });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://localhost:3000/dev/escalpos');
  const panel = page.getByTestId('console-escalpos');
  await panel.waitFor();
  assert.equal(await panel.locator('.hs-implant').count(), 4);
  assert.equal(await panel.getByRole('button', { name: /Meus implantes/ }).count(), 0);
  await page.screenshot({ path: '/tmp/escalpos-desktop.png', fullPage: true });
  await panel.getByRole('button', { name: 'Catálogo', exact: true }).click();
  const catalog = page.getByRole('dialog', { name: 'Catálogo de escalpos', exact: true });
  await catalog.waitFor();
  assert.equal(await catalog.locator('.cm-carta').count(), 39);
  assert.equal(await catalog.locator('.cm-corpo').count(), 1);
  await catalog.getByRole('button', { name: 'Ver Ouvidos de Caçador', exact: true }).click();
  assert.equal(await catalog.locator('.hs-modules details').count(), 3);
  await catalog.getByText('Cartografia Acústica', { exact: true }).click();
  await page.screenshot({ path: '/tmp/escalpos-catalog.png', fullPage: true });
  await catalog.getByRole('button', { name: 'Registrar instalação' }).click();
  await catalog.getByRole('button', { name: 'Voltar', exact: true }).click();
  await catalog.getByRole('button', { name: 'Registrar instalação' }).click();
  await catalog.getByRole('button', { name: 'Confirmar instalação' }).click();
  assert.equal(await panel.locator('.hs-implant').count(), 5);
  await catalog.getByRole('searchbox', { name: 'Buscar escalpo no catálogo' }).fill('bracos');
  assert.equal(await catalog.locator('.cm-carta').count(), 5);
  await catalog.getByRole('searchbox', { name: 'Buscar escalpo no catálogo' }).fill('inexistente');
  assert.equal(await catalog.locator('.cm-carta').count(), 0);
  await page.keyboard.press('Escape');
  await catalog.waitFor({ state: 'detached' });
  await panel.getByRole('button', { name: 'Ver Ouvidos de Caçador', exact: true }).last().click();
  const dossier = page.locator('.hs-dialog');
  await dossier.waitFor();
  await page.screenshot({ path: '/tmp/escalpos-detail.png', fullPage: true });
  await dossier.getByRole('button', { name: 'Remover instalação' }).click();
  await dossier.getByRole('button', { name: 'Confirmar remoção' }).click();
  assert.equal(await panel.locator('.hs-implant').count(), 4);
  await panel.getByRole('button', { name: 'Neurais: 1 implante' }).click();
  assert.equal(await panel.locator('.hs-implant').count(), 1);
  await panel.getByRole('button', { name: 'Todos os sistemas' }).click();
  await page.getByRole('checkbox', { name: 'Somente leitura' }).check();
  await panel.getByRole('button', { name: 'Ver Braços Gorila' }).click();
  assert.equal(await dossier.getByRole('button', { name: 'Remover instalação' }).count(), 0);
  await page.keyboard.press('Escape');
  assert.equal(await panel.getByRole('button', { name: 'Ver Braços Gorila' }).evaluate(el => document.activeElement === el), true);
  await page.getByRole('checkbox', { name: 'Catálogo indisponível' }).check();
  assert.equal(await panel.locator('.hs-implant').count(), 4);
  await page.getByRole('checkbox', { name: 'Catálogo indisponível' }).uncheck();
  await page.getByRole('button', { name: 'Ficha vazia' }).click();
  assert.match(await panel.innerText(), /Sem implantes/i);
  await page.screenshot({ path: '/tmp/escalpos-empty.png', fullPage: true });
  await page.getByRole('button', { name: 'Restaurar exemplo' }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '/tmp/escalpos-mobile.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await panel.getByRole('button', { name: 'Catálogo', exact: true }).click();
  await catalog.getByRole('button', { name: 'Ver Ouvidos de Caçador', exact: true }).click();
  await catalog.evaluate(async el => { await Promise.all(el.getAnimations({subtree:true}).filter(a => a.effect.getComputedTiming().iterations !== Infinity).map(a => a.finished.catch(() => {}))); });
  await page.screenshot({ path: '/tmp/escalpos-catalog-mobile.png', fullPage: true });
  await catalog.getByRole('button', { name: '← Voltar ao catálogo', exact: true }).click();
  await page.keyboard.press('Escape');
  await catalog.waitFor({ state: 'detached' });
  await page.setViewportSize({ width: 1200, height: 1000 });
  await page.getByRole('button', { name: 'Abrir no Console' }).click();
  await page.screenshot({ path: '/tmp/escalpos-console-main.png', fullPage: true });
  await panel.getByRole('button', { name: 'Catálogo', exact: true }).click();
  await catalog.getByRole('searchbox', { name: 'Buscar escalpo no catálogo' }).fill('filtro cognitivo');
  await catalog.getByRole('button', { name: 'Ver Filtro Cognitivo', exact: true }).click();
  await page.keyboard.press('Escape');
  await catalog.waitFor({ state: 'detached' });
  assert.equal(await page.locator('.rc-window').count(), 1);
  await panel.getByRole('button', { name: 'Guia de escalpos' }).click();
  await dossier.getByRole('button', { name: 'Fechar', exact: true }).focus();
  await page.keyboard.press('Shift+Tab');
  assert.equal(await dossier.evaluate(el => el.contains(document.activeElement)), true);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('.rc-window').count(), 1);
  assert.deepEqual(errors, []);
  console.log('Escalpos: janela compartilhada de catálogo, ficha de item, instalação, remoção, filtros, leitura, falha, vazio, mobile e Console OK.');
} finally { await browser.close(); }
