import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const browser = await chromium.launch({headless:true});
try {
 const page = await browser.newPage({viewport:{width:1100,height:1100},reducedMotion:'reduce'});
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://localhost:3000/dev/identidade');
 const panel=page.getByRole('region',{name:'Identidade do personagem'});
 await panel.waitFor();
 assert.equal(await panel.locator('.hx-cartao-magia').count(),5);
 assert.ok(await panel.getByText('Beldrano',{exact:false}).count());
 assert.ok(await panel.getByText('Beldran',{exact:false}).count());
 await panel.getByRole('button',{name:/Contato/}).click();
 await page.getByRole('dialog').getByText('Nilo',{exact:true}).waitFor();
 await page.keyboard.press('Escape');await page.getByRole('dialog').waitFor({state:'detached'});
 await page.screenshot({path:'/tmp/identidade-desktop.png',fullPage:true});
 await panel.getByRole('button',{name:/Infiltrador/}).click();
 const dialog=page.getByRole('dialog');await dialog.waitFor();
 assert.ok(await dialog.locator('.hi-habilidades').count()>0);
 await page.keyboard.press('Escape');await dialog.waitFor({state:'detached'});
 const edit=panel.getByRole('button',{name:'Editar dossiê'});await edit.click();
 await dialog.getByLabel('Objetivo atual',{exact:true}).fill('Encontrar a irmã desaparecida.');
 await dialog.getByLabel('Situação do RPI',{exact:true}).selectOption('sinalizado');
 await page.evaluate(async () => { await Promise.all(document.getAnimations().filter(a => a.effect?.getComputedTiming().iterations !== Infinity).map(a => a.finished.catch(() => {}))); });
 await page.screenshot({path:'/tmp/identidade-editor.png',fullPage:true});
 await dialog.getByRole('button',{name:'Salvar dossiê'}).click();await dialog.waitFor({state:'detached'});
 assert.equal(await panel.getByText('Encontrar a irmã desaparecida.',{exact:true}).count(),1);
 assert.ok(await panel.locator('.hi-status').getByText('Sinalizado').isVisible());
 await edit.click(); await dialog.getByLabel('Objetivo atual',{exact:true}).fill('Descartar alteração');
 await dialog.getByRole('button',{name:'Cancelar',exact:true}).click();await dialog.waitFor({state:'detached'});
 assert.equal(await panel.getByText('Encontrar a irmã desaparecida.',{exact:true}).count(),1);
 await page.getByLabel('Somente leitura').check(); assert.equal(await edit.count(),0);
 await page.getByRole('button',{name:'Ficha vazia',exact:true}).click();
 assert.ok(await panel.getByText('Subclasse não escolhida').isVisible());
 assert.equal(await panel.getByText('Sua história começa com quem você escolhe ser.').count(),0);
 assert.ok(await panel.getByText('Nenhuma qualidade escolhida.').isVisible());
 await page.getByRole('button',{name:'Restaurar exemplo'}).click();
 await page.setViewportSize({width:1000,height:850});
 await page.getByRole('button',{name:'Abrir no Console',exact:true}).click();
 const scroller=page.locator('.rc-tabpanel');await scroller.waitFor();
 await page.evaluate(async()=>{await Promise.all(document.getAnimations().filter(a=>a.effect?.getComputedTiming().iterations!==Infinity).map(a=>a.finished.catch(()=>{})));});
 assert.ok(await scroller.evaluate(el=>el.scrollWidth<=el.clientWidth+1));
 assert.ok(await panel.evaluate(el=>el.scrollHeight<=el.clientHeight+2));
 await page.screenshot({path:'/tmp/identidade-console.png',fullPage:true});
 await scroller.evaluate(el=>el.scrollTop=el.scrollHeight);
 assert.ok(await scroller.evaluate(el=>Math.abs(el.scrollHeight-el.clientHeight-el.scrollTop)<2));
 await page.screenshot({path:'/tmp/identidade-console-scroll.png',fullPage:true});
 await page.getByRole('button',{name:'Fechar console',exact:true}).click();
 await scroller.waitFor({state:'detached'});
 await page.setViewportSize({width:390,height:844});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:'/tmp/identidade-mobile.png',fullPage:true});
 assert.deepEqual(errors,[]); console.log('Identidade: cards, detalhes, edição, cancelamento, leitura e mobile OK.');
} finally {await browser.close();}
