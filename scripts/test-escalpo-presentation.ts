import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { dadosEscalpo, regiaoEscalpo } from "../src/lib/character/escalpoPresentation";
import { normalizeTechnicalContentItem } from "../src/lib/content/technicalLibrary";
const db = JSON.parse(readFileSync("content/v12/db_mercado_escalpos_v1_2.json", "utf8"));
const catalogo = db.escalpos.map(normalizeTechnicalContentItem);
const model = (nome: string) => catalogo.find((e: { nome: string }) => e.nome === nome)!;
assert.equal(dadosEscalpo(model("Ouvidos de Caçador")).integridade, 1);
assert.equal(dadosEscalpo(model("Ouvidos de Caçador")).modulos, 2);
assert.equal(dadosEscalpo(model("Ouvidos de Caçador")).espacos, 1);
assert.equal(dadosEscalpo(model("Filtro Cognitivo")).modulos, 1);
assert.equal(dadosEscalpo(model("Neuroprocessador")).integridade, 0);
assert.equal(dadosEscalpo(model("Deck Sináptico Imperial")).integridade, 3);
assert.ok(dadosEscalpo(model("Deck Sináptico Imperial")).linhas.some(([k]) => k === "Comandos"));
assert.equal(dadosEscalpo(model("RPI Forjado (Nível 1)")).integridade, null);
assert.equal(dadosEscalpo(undefined).integridade, null);
assert.equal(dadosEscalpo(undefined).modulos, null);
assert.equal(regiaoEscalpo(undefined).id, "outros");
const conflicting = normalizeTechnicalContentItem({ custo_integridade: 0, descricao_longa: "**Integridade:** –2\n\n### MÓDULOS\n\n**Integridade:** –9" });
assert.equal(dadosEscalpo(conflicting).integridade, 0, "Campo explícito tem precedência, inclusive zero.");
const moduleOnly = normalizeTechnicalContentItem({ descricao_longa: "Descrição do implante\n\n### MÓDULOS\n\n**Integridade:** –9" });
assert.equal(dadosEscalpo(moduleOnly).integridade, null, "Não extrair custo de outro verbete.");
assert.doesNotMatch(dadosEscalpo(model("Ouvidos de Caçador")).descricao, /Dados da lista|MÓDULOS|Preço:|Integridade:/);
console.log("Apresentação dos escalpos: campos explícitos, custos editoriais, variantes, módulos e ausência de dados OK.");
