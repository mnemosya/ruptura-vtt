import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { itemDescription } from "../src/lib/character/itemDescription";

const payload = JSON.parse(readFileSync("content/v12/revisao-2026-10-10-atualizada/db_mercado_itens_v1_2.json", "utf8"));
const items = Object.values(payload).find(Array.isArray) as { nome: string; descricao_longa?: string; descricao_curta?: string }[];
const find = (name: string) => { const item = items.find(i => i.nome === name); assert.ok(item, name); return item; };
const dagger = itemDescription(find("Adaga"), ["Dano", "Mãos", "Propriedades", "Ocultável"]);
assert.match(dagger, /lâmina dupla/);
assert.doesNotMatch(dagger, /Dano:|Mãos:|Propriedades:|Ocultável:|Preço:|Dados da lista/);
const buckle = itemDescription(find("Fivela de Retorno"));
assert.match(buckle, /Uma vez por cena/);
assert.match(buckle, /10 m/);
assert.match(buckle, /segurados por outra criatura/);
assert.doesNotMatch(buckle, /Espaços:|Preço:|Raridade:/);
const blocker = itemDescription(find("Bloqueador de sinal"));
assert.match(blocker, /Não afeta gravação local/);
assert.match(blocker, /dispositivos ligados por cabo/);
const trousers = itemDescription(find("Calça acolchoada"), ["Cobertura", "MIT", "Proteção", "Ocultável"]);
assert.match(trousers, /camadas de enchimento/);
assert.doesNotMatch(trousers, /Região:|Mitigação|Resistência:|Ocultável:|Preço:|Espaços:/);
const medkit = itemDescription(find("Medkit"), ["Custo"]);
assert.match(medkit, /Em falha, recupera metade/);
assert.match(medkit, /3 usos/);
assert.doesNotMatch(medkit, /PA para uso:|Imagem no Notion/);
const icarus = itemDescription(find("Icarus I"));
assert.match(icarus, /Propulsão aérea/);
assert.match(icarus, /Recarga/);
assert.match(icarus, /começa a cair/);
assert.equal(itemDescription({ descricao_longa: "  ", descricao_curta: "Resumo." }), "Resumo.");
assert.match(itemDescription({ descricao_longa: "**Cargas:** 3\n\n**Recarga:** durante o descanso." }), /Cargas/);
assert.doesNotMatch(itemDescription({ descricao_longa: "**Cargas:** 3\n\n**Recarga:** durante o descanso." }, ["Cargas"]), /Cargas/);
for (const item of items) assert.doesNotMatch(itemDescription(item), /Dados da lista de mercadorias:|\[Imagem no Notion\]/i, item.nome);
console.log(`✓ ${items.length} descrições sem apêndices de importação; regras completas preservadas e estatísticas deduplicadas conforme o card`);
